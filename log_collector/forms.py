class LogCollectorApiTokenForm(forms.ModelForm):
    class Meta:
        model = LogCollectorApiToken
        fields = (
            "name",
            "expires_at",
            "allowed_ip_address",
            "allowed_origin_domain",
        )
        widgets = {
            "expires_at": forms.DateTimeInput(attrs={"type": "datetime-local"}),
        }

    def clean_allowed_ip_address(self):
        value = (self.cleaned_data.get("allowed_ip_address") or "").strip()
        if not value:
            return ""
        try:
            ipaddress.ip_network(value, strict=False)
        except ValueError as exc:
            raise forms.ValidationError("Enter a valid IP address or CIDR range.") from exc
        return value

    def clean_allowed_origin_domain(self):
        value = (self.cleaned_data.get("allowed_origin_domain") or "").strip().lower()
        if not value:
            return ""
        if "://" in value:
            parsed = urlsplit(value)
            value = parsed.netloc
        value = value.split("/", 1)[0].split(":", 1)[0].strip(".")
        if not value or " " in value or "." not in value:
            raise forms.ValidationError("Enter a valid domain name.")
        return value

    def save(self, entity, created_by=None):
        return LogCollectorApiToken.create_token(
            entity=entity,
            name=self.cleaned_data["name"],
            created_by=created_by,
            expires_at=self.cleaned_data.get("expires_at"),
            allowed_ip_address=self.cleaned_data.get("allowed_ip_address") or "",
            allowed_origin_domain=self.cleaned_data.get("allowed_origin_domain") or "",
        )
