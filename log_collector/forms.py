import ipaddress
from urllib.parse import urlsplit

from django import forms
from django.utils.text import slugify

from log_collector.models import (
    LogCollectorApiToken,
    LogCollectorEntity,
    LogCollectorIntegratedDomain,
    LogCollectorSettings,
)


class EntityForm(forms.ModelForm):
    slug = forms.SlugField(
        required=False,
        label="Local management slug",
        help_text="Used only for this collector's local management URLs. Leave blank to generate a unique slug from the remote collector URL and remote entity slug.",
    )
    remote_entity_slug = forms.SlugField(
        required=False,
        label="Remote entity slug",
        help_text="The entity slug exposed by the remote collector, usually hosting-app.",
    )

    class Meta:
        model = LogCollectorEntity
        fields = (
            "name",
            "slug",
            "is_active",
            "api_base_url",
            "remote_entity_slug",
            "remote_api_key",
            "access_logs_enabled",
            "geolocation_enabled",
            "user_sessions_enabled",
            "enable_api_endpoint",
        )
        widgets = {
            "remote_api_key": forms.PasswordInput(attrs={"autocomplete": "new-password"}),
        }
        labels = {
            "api_base_url": "Remote collector base URL",
            "remote_entity_slug": "Remote entity slug",
            "remote_api_key": "Remote API token generated by the remote collector",
        }
        help_texts = {
            "api_base_url": "The remote app origin, for example https://collector.example.com.",
            "remote_entity_slug": "The entity slug exposed by the remote collector, usually hosting-app.",
            "remote_api_key": "Paste a token generated by the remote collector. The saved token is never displayed.",
        }

    def clean_remote_api_key(self):
        value = self.cleaned_data.get("remote_api_key", "")
        if not value and self.instance.pk:
            return self.instance.remote_api_key
        return value

    def clean(self):
        cleaned_data = super().clean()
        remote_entity_slug = (cleaned_data.get("remote_entity_slug") or "").strip()
        if self.instance.pk and self.instance.is_hosting:
            cleaned_data["remote_entity_slug"] = self.instance.remote_entity_slug
        elif not remote_entity_slug:
            self.add_error("remote_entity_slug", "This field is required.")

        if cleaned_data.get("slug"):
            return cleaned_data

        if self.instance.pk and self.instance.is_hosting:
            self.add_error("slug", "This field is required.")
            return cleaned_data

        remote_url = cleaned_data.get("api_base_url", "")
        remote_slug = cleaned_data.get("remote_entity_slug", "")
        hostname = urlsplit(remote_url).hostname or "remote"
        base_slug = slugify(f"{hostname}-{remote_slug}") or "remote-entity"
        cleaned_data["slug"] = self._unique_local_slug(base_slug)
        return cleaned_data

    def _unique_local_slug(self, base_slug):
        base_slug = base_slug[:120]
        queryset = LogCollectorEntity.objects.exclude(pk=self.instance.pk)
        if not queryset.filter(slug=base_slug).exists():
            return base_slug

        suffix = 2
        while True:
            candidate = f"{base_slug[:120 - len(str(suffix)) - 1]}-{suffix}"
            if not queryset.filter(slug=candidate).exists():
                return candidate
            suffix += 1


